def write_templates(output, force=False):
    root = Path(output)
    paths = [root / (spec[0] + ".md") for spec in SPECS]
    index = root / "README.md"
    require(force or not any(p.exists() for p in paths + [index]), "Template files exist; use --force to regenerate")
    root.mkdir(parents=True, exist_ok=True)
    for path, spec in zip(paths, SPECS):
        path.write_text(template_text(spec), encoding="utf-8")
    lines = ["# QTest 详细报告模板索引", "", "模板 v3，共 9 类。用于定义报告应包含的内容；未实现的测试插件在模板中明确标记。", ""]
    for path, spec in zip(paths, SPECS):
        lines.append(f"- [{spec[1]}]({path.name})：{spec[2]}。")
    lines.extend(["", "实际运行使用 qtest report 自动生成含证据的 Markdown 与 JSON，再用 qtest compare 批量汇总；模板本身不作为测试结果导入。", ""])
    index.write_text("\n".join(lines), encoding="utf-8")
    return {"directory": str(root.resolve()), "templates": len(paths), "index": str(index.resolve())}
